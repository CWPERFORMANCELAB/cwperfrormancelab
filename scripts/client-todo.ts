import type { PlaceholderItem } from "../src/lib/placeholders";

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

/** Generates CLIENT_TODO.md from the placeholder scan plus the non-code items the client must action. */
export function renderClientTodo(items: PlaceholderItem[]): string {
  const areas = ["Business details", "Brand", "Settings", "Services", "Content", "Media", "Legal"] as const;
  let md = `# CLIENT TODO — CW Performance Lab

_Generated by \`npm run check:placeholders -- --write\`. Don't edit the tables by hand; fix the source and re-run._

Everything below is running on a **placeholder** value. Once Christopher confirms a detail, update the file shown,
then run \`npm run apply:client-details\` (for settings/services) and \`npm run check:placeholders\`.
See **UPDATING-CLIENT-DETAILS.md** for exactly where each detail goes.

**${items.length} placeholders remaining.**
`;
  for (const area of areas) {
    const list = items.filter((i) => i.area === area);
    if (!list.length) continue;
    md += `\n## ${area}\n\n| What | Current value | File | Needed from client |\n| --- | --- | --- | --- |\n`;
    for (const i of list) md += `| ${esc(i.what)} | ${esc(i.current)} | \`${esc(i.file)}\` | ${esc(i.needed)} |\n`;
  }
  md += `
## Also needed (not stored as placeholders)

| Item | Why | Action |
| --- | --- | --- |
| **Phone & email are temporary personal details** | 07476243133 / christophwilliams14@gmail.com are being replaced | Provide the new business number and email; update \`config/business.ts\` |
| **ICO registration** | He processes health (special category) data, so he very likely needs to register with the ICO and pay the data protection fee | Register at ico.org.uk; add the number to \`config/business.ts → legal.icoRegistration\` |
| **VAT position** | Services are set to no VAT. Confirm with an accountant (sport rehab/massage may be standard-rated; VAT registration threshold applies) | Confirm; set \`paymentDefaults.defaultTaxRateBp\` or per-service \`taxRateBp\` |
| **Data retention period** | Clinical records are retained for 8 years (adults) / until age 25 (under-18s) as a placeholder | Confirm against BASRaT guidance and his insurer |
| **Professional indemnity insurance** | Usually required to be stated in terms | Provide insurer name if he wants it shown |
| **Existing Calendly bookings & vouchers** | Must be honoured after switch-over | Export from Calendly. See MIGRATION.md |
| **Stripe account** | Live keys, Apple Pay domain verification, payout bank account | Complete Stripe onboarding (go-live checklist in README) |
| **Sending domain** | Emails need SPF/DKIM/DMARC on the new domain | Done with the domain setup |
| **Google Business Profile** | Review link + local SEO | Claim/verify profile; add review link to \`config/business.ts\` |
| **Intake & consent wording** | Red-flag, cupping and compression questions are sensible clinical defaults | Christopher to review \`src/lib/booking/questions.ts\` |
| **Legal pages** | Privacy/terms/cookie wording is a solid draft, not legal advice | Have them reviewed |
`;
  return md;
}
